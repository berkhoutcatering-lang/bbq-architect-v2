-- ─── 5. Materialized view: gerecht_allergens_mv ──────────────
-- Cascade: ingredient → component → gerecht
-- source_chain bevat de bewijs-keten voor EU 1169/2011 audit.

CREATE MATERIALIZED VIEW IF NOT EXISTS gerecht_allergens_mv AS
SELECT
    gc.gerecht_id,
    gc.organization_id,
    ia.allergen_code,
    bool_or(ia.confirmed_at IS NOT NULL) AS any_confirmed,
    bool_or(ia.ai_suggested AND ia.confirmed_at IS NULL) AS has_unconfirmed_ai,
    jsonb_agg(DISTINCT jsonb_build_object(
        'inventory_id', ci.inventory_id,
        'fallback_name', ci.fallback_name,
        'component_id', gc.component_id,
        'confirmed', ia.confirmed_at IS NOT NULL,
        'ai_suggested', ia.ai_suggested
    )) AS source_chain
FROM gerecht_components gc
JOIN component_ingredients ci ON ci.component_id = gc.component_id
JOIN ingredient_allergens ia ON ia.inventory_id = ci.inventory_id
GROUP BY gc.gerecht_id, gc.organization_id, ia.allergen_code;

-- Note: materialized views in Postgres ondersteunen geen UNIQUE INDEX op een
-- view zonder REFRESH MATERIALIZED VIEW CONCURRENTLY. Daarom maken we hem
-- expliciet ondersteunend voor concurrent refresh.
CREATE UNIQUE INDEX IF NOT EXISTS idx_gerecht_allergens_mv_pk
    ON gerecht_allergens_mv (gerecht_id, allergen_code);

CREATE INDEX IF NOT EXISTS idx_gerecht_allergens_mv_org
    ON gerecht_allergens_mv (organization_id);

COMMENT ON MATERIALIZED VIEW gerecht_allergens_mv IS
    'Pillar #2: cascade ingredient→component→gerecht voor allergenen. '
    'source_chain levert EU 1169/2011 audit-evidence. Refresh via refresh_gerecht_allergens_mv().';

-- ─── 6. Helper: refresh on demand ────────────────────────────

CREATE OR REPLACE FUNCTION refresh_gerecht_allergens_mv()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    -- CONCURRENTLY = niet-blocking voor readers. Vereist unique index (zie boven).
    REFRESH MATERIALIZED VIEW CONCURRENTLY gerecht_allergens_mv;
EXCEPTION
    WHEN OTHERS THEN
        -- Fall back op non-concurrent refresh als concurrent faalt (bv. eerste refresh)
        REFRESH MATERIALIZED VIEW gerecht_allergens_mv;
END;
$$;

COMMENT ON FUNCTION refresh_gerecht_allergens_mv() IS
    'On-demand refresh van gerecht_allergens_mv. Roept Server Actions aan na '
    'mutaties op ingredient_allergens of component_ingredients. '
    'CONCURRENTLY zodat readers niet blokkeren.';

-- ─── 7. Trigger-glue: auto-refresh bij allergen/ingredient changes ──
-- Trigger het MV-refresh statement nadat een rij wijzigt. Voor lage write-volume
-- (component-curatie, allergen-bevestiging) is dit acceptabel. Bij hogere
-- write-volume kunnen we naar een job-queue verschuiven.

CREATE OR REPLACE FUNCTION trigger_refresh_gerecht_allergens()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    -- Asynchroon zou ideaal zijn maar pg_notify + worker is overkill voor v1.
    -- Refresh inline; concurrent zorgt dat readers niet blokkeren.
    PERFORM refresh_gerecht_allergens_mv();
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_refresh_mv_on_ingredient_allergens ON ingredient_allergens;
CREATE TRIGGER trg_refresh_mv_on_ingredient_allergens
    AFTER INSERT OR UPDATE OR DELETE ON ingredient_allergens
    FOR EACH STATEMENT
    EXECUTE FUNCTION trigger_refresh_gerecht_allergens();

DROP TRIGGER IF EXISTS trg_refresh_mv_on_component_ingredients ON component_ingredients;
CREATE TRIGGER trg_refresh_mv_on_component_ingredients
    AFTER INSERT OR UPDATE OR DELETE ON component_ingredients
    FOR EACH STATEMENT
    EXECUTE FUNCTION trigger_refresh_gerecht_allergens();

DROP TRIGGER IF EXISTS trg_refresh_mv_on_gerecht_components ON gerecht_components;
CREATE TRIGGER trg_refresh_mv_on_gerecht_components
    AFTER INSERT OR UPDATE OR DELETE ON gerecht_components
    FOR EACH STATEMENT
    EXECUTE FUNCTION trigger_refresh_gerecht_allergens();

-- ─── 8. Helper: backfill ingredient_allergens uit inventory.allergenen ──
-- inventory.allergenen is een legacy text[] kolom. Migrate naar genormaliseerde join.
-- ai_suggested=false voor bestaande data (mens heeft ze ooit gezet) — maar
-- confirmed_at=NULL zodat de UI weet ze nog tonen voor revisit.

CREATE OR REPLACE FUNCTION backfill_ingredient_allergens()
RETURNS TABLE (inserted_count INTEGER, skipped_count INTEGER)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_inserted INTEGER := 0;
    v_skipped INTEGER := 0;
    v_rec RECORD;
    v_allergen TEXT;
    v_org_id UUID;
    v_normalized TEXT;
BEGIN
    FOR v_rec IN
        SELECT i.id AS inventory_id, i.allergenen, i.organization_id
        FROM inventory i
        WHERE i.allergenen IS NOT NULL
          AND array_length(i.allergenen, 1) > 0
          AND i.organization_id IS NOT NULL
    LOOP
        v_org_id := v_rec.organization_id;

        FOREACH v_allergen IN ARRAY v_rec.allergenen
        LOOP
            -- Normaliseer (lowercase, trim) en map naar allergen-code.
            v_normalized := LOWER(TRIM(v_allergen));
            -- Probeer eerst exact-match op nl_label, dan op code.
            DECLARE
                v_code TEXT;
            BEGIN
                SELECT code INTO v_code FROM allergens
                WHERE LOWER(nl_label) = v_normalized
                   OR LOWER(code) = v_normalized
                LIMIT 1;

                IF v_code IS NULL THEN
                    v_skipped := v_skipped + 1;
                    CONTINUE;
                END IF;

                INSERT INTO ingredient_allergens (
                    inventory_id, allergen_code, organization_id,
                    ai_suggested, confirmed_at
                ) VALUES (
                    v_rec.inventory_id, v_code, v_org_id,
                    false, NULL  -- bestaande data → niet AI, maar wel revisit-needed
                )
                ON CONFLICT (inventory_id, allergen_code) DO NOTHING;

                IF FOUND THEN
                    v_inserted := v_inserted + 1;
                END IF;
            END;
        END LOOP;
    END LOOP;

    RETURN QUERY SELECT v_inserted, v_skipped;
END;
$$;

COMMENT ON FUNCTION backfill_ingredient_allergens() IS
    'One-shot migration helper: kopieert inventory.allergenen[] naar ingredient_allergens. '
    'Run ÉÉN keer na deze migration met SELECT * FROM backfill_ingredient_allergens(); '
    'Idempotent (ON CONFLICT DO NOTHING).';

