-- ─── 2. ingredient_allergens — join inventory ↔ allergens ────
-- Hard-rule 2: AI suggereert (ai_suggested=true), mens bevestigt (confirmed_at).
-- Dit is de SOURCE OF TRUTH voor allergens-per-ingredient.

CREATE TABLE IF NOT EXISTS ingredient_allergens (
    inventory_id     INTEGER NOT NULL REFERENCES inventory(id) ON DELETE CASCADE,
    allergen_code    TEXT    NOT NULL REFERENCES allergens(code) ON DELETE RESTRICT,
    organization_id  UUID    NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,

    ai_suggested     BOOLEAN NOT NULL DEFAULT false,
    confirmed_at     TIMESTAMPTZ,
    confirmed_by     UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    notes            TEXT,

    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (inventory_id, allergen_code)
);

CREATE INDEX IF NOT EXISTS idx_ingredient_allergens_org ON ingredient_allergens(organization_id);
CREATE INDEX IF NOT EXISTS idx_ingredient_allergens_inventory ON ingredient_allergens(inventory_id);

COMMENT ON TABLE ingredient_allergens IS
    'Allergeen per ingredient (inventory-item). AI mag voorstellen (ai_suggested=true), '
    'mens bevestigt (confirmed_at set). Dit is de FUNDAMENT van de cascade ingredient→component→gerecht.';

-- ─── 3. component_ingredients — join components ↔ inventory ──
-- Normaliseert components.ingredients JSONB naar een echte FK.
-- Bestaande JSONB-data blijft 1 release, helper-function backfilled.

CREATE TABLE IF NOT EXISTS component_ingredients (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_id     BIGINT NOT NULL REFERENCES components(id) ON DELETE CASCADE,
    inventory_id     INTEGER REFERENCES inventory(id) ON DELETE RESTRICT,
    organization_id  UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,

    -- Voor unmatched items (AI heeft een ingredient genoemd dat niet in inventory zit)
    -- mag inventory_id NULL zijn. Dan vult fallback_name de naam in.
    fallback_name    TEXT,
    quantity         NUMERIC(10,3) NOT NULL CHECK (quantity > 0),
    unit             TEXT NOT NULL,
    -- Yield-override per gebruik (default = inventory.yield_factor).
    -- Pillar #1 research: dubbele yield-loss aware foodcost (raw × prep).
    yield_override   NUMERIC(5,3),

    notes            TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_inventory_or_fallback CHECK (
        inventory_id IS NOT NULL OR fallback_name IS NOT NULL
    )
);

CREATE INDEX IF NOT EXISTS idx_component_ingredients_component ON component_ingredients(component_id);
CREATE INDEX IF NOT EXISTS idx_component_ingredients_inventory ON component_ingredients(inventory_id) WHERE inventory_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_component_ingredients_org ON component_ingredients(organization_id);

COMMENT ON TABLE component_ingredients IS
    'Genormaliseerde ingredient-link van components naar inventory. '
    'Vervangt components.ingredients JSONB. Bij geen inventory-match: fallback_name. '
    'yield_override laat per-gebruik prep-yield variatie toe (apart van inventory.yield_factor).';

-- ─── 4. RLS op nieuwe joins ─────────────────────────────────

ALTER TABLE ingredient_allergens   ENABLE ROW LEVEL SECURITY;
ALTER TABLE component_ingredients  ENABLE ROW LEVEL SECURITY;

DO $rls$
DECLARE
    tbl TEXT;
    org_check TEXT := 'organization_id IN (SELECT om.organization_id FROM public.organization_members om WHERE om.user_id = (SELECT auth.uid()) AND om.status = ''active'')';
BEGIN
    FOR tbl IN
        SELECT unnest(ARRAY['ingredient_allergens', 'component_ingredients'])
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS "org_select" ON %I', tbl);
        EXECUTE format('DROP POLICY IF EXISTS "org_insert" ON %I', tbl);
        EXECUTE format('DROP POLICY IF EXISTS "org_update" ON %I', tbl);
        EXECUTE format('DROP POLICY IF EXISTS "org_delete" ON %I', tbl);

        EXECUTE format('CREATE POLICY "org_select" ON %I FOR SELECT USING (%s)', tbl, org_check);
        EXECUTE format('CREATE POLICY "org_insert" ON %I FOR INSERT WITH CHECK (%s)', tbl, org_check);
        EXECUTE format('CREATE POLICY "org_update" ON %I FOR UPDATE USING (%s)', tbl, org_check);
        EXECUTE format('CREATE POLICY "org_delete" ON %I FOR DELETE USING (%s)', tbl, org_check);
    END LOOP;
END
$rls$;

