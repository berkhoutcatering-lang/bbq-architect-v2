-- Standaard org-scoped policies — INLINE subquery (geen helper-functie)
-- voor robuustheid tegen ontbrekend/locked auth-schema.
DO $rls$
DECLARE
    tbl TEXT;
    org_check TEXT := 'organization_id IN (SELECT om.organization_id FROM public.organization_members om WHERE om.user_id = auth.uid() AND om.status = ''active'')';
BEGIN
    FOR tbl IN
        SELECT unnest(ARRAY[
            'components',
            'supplier_products',
            'component_allergens',
            'component_haccp_points',
            'gerecht_components'
        ])
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS "org_select" ON %I', tbl);
        EXECUTE format('DROP POLICY IF EXISTS "org_insert" ON %I', tbl);
        EXECUTE format('DROP POLICY IF EXISTS "org_update" ON %I', tbl);
        EXECUTE format('DROP POLICY IF EXISTS "org_delete" ON %I', tbl);

        EXECUTE format('CREATE POLICY "org_select" ON %I FOR SELECT USING (%s)', tbl, org_check);
        EXECUTE format('CREATE POLICY "org_insert" ON %I FOR INSERT WITH CHECK (%s)', tbl, org_check);
        EXECUTE format('CREATE POLICY "org_update" ON %I FOR UPDATE USING (%s)', tbl, org_check);
        EXECUTE format('CREATE POLICY "org_delete" ON %I FOR DELETE USING (%s)', tbl, org_check);
    END LOOP;
END
$rls$;

